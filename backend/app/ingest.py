# A line that is NOTHING but a control code (1-4 dot/hyphen-separated
# segments after the first) or one of the two structural row labels this
# table format uses. Requiring the WHOLE line to match is what keeps this
# from false-matching numbers inside flowing prose.
_BARE_CODE_OR_LABEL = re.compile(r"^(\d+(?:[-.]\d+){1,4}|Objective|Controls)$")

# A subcontrol code immediately followed by its own text on the SAME line
# (ECC-2:2024's dotted subcontrols only — e.g. "1.5.3.1 At early stage of
# technology projects."). Depth >= 3 (2+ repetitions) to avoid catching an
# unrelated short numbered fragment.
_INLINE_CODE = re.compile(r"^(\d+(?:\.\d+){2,4})\s+(.+)$")

# "Objective" sometimes leads straight into its own text on the same line
# rather than sitting alone (e.g. ECC-2:2024: "Objective To ensure
# managing cybersecurity risks...") — without matching this explicitly it
# falls through to plain text and contaminates whatever clause is
# currently pending with the word "Objective" plus the objective prose.
# "Controls" was never observed with trailing text on the same line, but
# is included for symmetry/safety.
_INLINE_LABEL = re.compile(r"^(Objective|Controls)\s+(.+)$")

_DISCARD_LABELS = {"Objective", "Controls"}

# Header/footer chrome repeated on every page — filtered at the block
# level before any code/text parsing runs, so it can never leak into a
# clause's stored text (case-insensitive: ECC-1:2018 capitalizes
# "Classification", ECC-2:2024 doesn't).
_NOISE_SUBSTRINGS = [
    "essential cybersecurity controls",
    "sharing indicator",
    "document classification",
    "tlp:",
]


def _is_noise_block(text: str) -> bool:
    stripped = text.strip()
    if not stripped:
        return True
    if stripped.isdigit() and len(stripped) <= 3:  # bare page number
        return True
    lowered = stripped.lower()
    if any(pat in lowered for pat in _NOISE_SUBSTRINGS):
        return True
    if len(stripped) < 20 and not re.search(r"[A-Za-z0-9]", stripped):
        return True  # short Arabic-only watermark/label with no Latin/digit content
    return False


def extract_blocks(pdf_path: Path) -> list[dict]:
    """Text blocks in document order, each tagged with its page number,
    with header/footer chrome already filtered out."""
    doc = fitz.open(str(pdf_path))
    out: list[dict] = []
    for page_num in range(len(doc)):
        for x0, y0, x1, y1, text, bno, btype in doc[page_num].get_text("blocks"):
            if btype != 0:
                continue  # image block
            if _is_noise_block(text):
                continue
            out.append({"page": page_num + 1, "text": text})
    doc.close()
    return out


def parse_ecc_clauses(blocks: list[dict], code_before_text: bool) -> list[dict]:
    """Returns dicts with clause_id, text_en, page_en (parent_clause_id and
    order_index are added by a second pass below, and by
    _dedupe_and_resolve_parents — see the module docstring for why parent
    resolution can't happen in the same pass as extraction)."""
    raw: list[dict] = []

    if code_before_text:
        pending_id: str | None = None
        pending_text: list[str] = []
        pending_page: int | None = None
        discard = False

        def flush() -> None:
            nonlocal pending_id, pending_text, pending_page, discard
            if pending_id is not None and not discard:
                text = re.sub(r"\s+", " ", " ".join(pending_text)).strip()
                if text:
                    raw.append({"clause_id": pending_id, "text_en": text, "page_en": pending_page})
            pending_id, pending_text, discard = None, [], False

        for block in blocks:
            for line in (ln.strip() for ln in block["text"].split("\n")):
                if not line:
                    continue
                bare = _BARE_CODE_OR_LABEL.match(line)
                inline_label = _INLINE_LABEL.match(line)
                inline_code = _INLINE_CODE.match(line)
                if bare:
                    flush()
                    label = bare.group(1)
                    discard = label in _DISCARD_LABELS
                    pending_id = label
                    pending_page = block["page"]
                elif inline_label:
                    flush()
                    discard = True
                    pending_id = inline_label.group(1)
                    pending_text = [inline_label.group(2)]
                    pending_page = block["page"]
                elif inline_code:
                    flush()
                    pending_id = inline_code.group(1)
                    pending_text = [inline_code.group(2)]
                    pending_page = block["page"]
                    flush()
                elif pending_id is not None:
                    pending_text.append(line)
        flush()

    else:
        pending_text: list[str] = []
        pending_page: int | None = None
        dropped_empty: list[dict] = []  # bare codes whose accumulated text was empty — candidates for recovery

        for block in blocks:
            for line in (ln.strip() for ln in block["text"].split("\n")):
                if not line:
                    continue
                bare = _BARE_CODE_OR_LABEL.match(line)
                inline_label = _INLINE_LABEL.match(line)
                inline_code = _INLINE_CODE.match(line)
                if bare:
                    label = bare.group(1)
                    text = re.sub(r"\s+", " ", " ".join(pending_text)).strip()
                    if label not in _DISCARD_LABELS:
                        if text:
                            raw.append({"clause_id": label, "text_en": text, "page_en": pending_page})
                        else:
                            dropped_empty.append({"clause_id": label, "page_en": pending_page})
                    pending_text, pending_page = [], None
                elif inline_label:
                    # Not observed in a text-before-code document (there,
                    # a label's own text always precedes it on an earlier
                    # line — see module docstring), but handled the same
                    # way as a bare label for robustness: whatever was
                    # pending before this line can't belong to a label
                    # that also carries its own trailing text, so it's
                    # dropped rather than misattributed, and the trailing
                    # text starts fresh accumulation for whatever code
                    # follows next.
                    pending_text, pending_page = [inline_label.group(2)], block["page"]
                elif inline_code:
                    # Not observed in a text-before-code document; degrade
                    # to plain text rather than silently dropping it.
                    if pending_page is None:
                        pending_page = block["page"]
                    pending_text.append(line)
                else:
                    if pending_page is None:
                        pending_page = block["page"]
                    pending_text.append(line)
        # any text left over with no closing code (front matter/footer
        # stragglers before the first real row) is intentionally dropped

        raw = _recover_dropped_parent_intros(raw, dropped_empty)

    return _dedupe_and_resolve_parents(raw)


# A tall/merged parent row's own lead-in sentence always ends in a colon
# before its enumerated sub-items begin (confirmed against both real
# examples in the source PDF: "...must include at least the following:" —
# not assumed). An earlier version of this recovery tried to split on
# SOURCE BLOCK boundaries instead, on the theory that the intro and the
# first child's text land in separate PyMuPDF blocks — checking the real
# block dump disproved that: PyMuPDF also splits a single wrapped
# sentence ("...at least the \n" / "following: \n") across two blocks
# purely from line-wrapping in a narrow column, so block-counting would
# have cut the intro itself in half. The colon is the real signal.
_INTRO_LEAD_IN = re.compile(r"^(.{1,250}?:)\s+(.+)$", re.DOTALL)


def _recover_dropped_parent_intros(raw: list[dict], dropped_empty: list[dict]) -> list[dict]:
    """A tall/merged parent row (e.g. "2-5-3" spanning 8 sub-controls) in a
    text-before-code document accumulates NO text of its own — its intro
    sentence and its first child's own text both land in the same "text
    before the next code" run (see parse_ecc_clauses' text-before-code
    branch), with nothing but the colon marking where one ends and the
    other begins. For each parent whose own code was seen but produced
    empty text, split its earliest child's text at the first colon within
    a plausible intro-sentence length; the parent keeps the intro, the
    child keeps the rest. No colon found in a plausible position (or
    nothing left on either side of it) means nothing safe to split, so
    the parent stays dropped rather than guessing."""
    recovered: list[dict] = []

    for dropped in dropped_empty:
        parent_id = dropped["clause_id"]
        try:
            parent_segments = tuple(int(x) for x in re.split(r"[-.]", parent_id))
        except ValueError:
            continue

        candidates = [
            c for c in raw
            if len(re.split(r"[-.]", c["clause_id"])) == len(parent_segments) + 1
            and tuple(int(x) for x in re.split(r"[-.]", c["clause_id"]))[:-1] == parent_segments
        ]
        if not candidates:
            continue
        first_child = min(candidates, key=lambda c: raw.index(c))

        match = _INTRO_LEAD_IN.match(first_child["text_en"])
        if not match:
            continue
        intro_text, remaining_text = match.group(1).strip(), match.group(2).strip()
        if not intro_text or not remaining_text:
            continue

        first_child["text_en"] = remaining_text
        recovered.append({"clause_id": parent_id, "text_en": intro_text, "page_en": dropped["page_en"]})

    return raw + recovered


def _dedupe_and_resolve_parents(raw: list[dict]) -> list[dict]:
    # Some subdomain/domain codes appear twice — once in an early overview
    # table (short title only), once with real content later (see module
    # docstring). Keyed by NORMALIZED segments, not the raw clause_id
    # string: confirmed against the real data that ECC-2:2024 has at least
    # one domain header written inconsistently both ways for its two
    # occurrences ("1-7" in the overview table, "1.7" at its real content
    # further in the document — identical text, "Compliance with
    # Cybersecurity Standards, Laws and Regulations") — a string-keyed
    # dedup let both through as separate rows, which then broke exact-ID
    # alignment in diff.py (the overview-table duplicate "won" the
    # normalized-segment exact match there, leaving the real one
    # unmatched and misclassified as "new"). Keep whichever occurrence has
    # more substantive text; ties keep whichever was captured first.
    best_by_segments: dict[tuple[int, ...], dict] = {}
    for c in raw:
        segments = tuple(int(x) for x in re.split(r"[-.]", c["clause_id"]))
        existing = best_by_segments.get(segments)
        if existing is None or len(c["text_en"]) > len(existing["text_en"]):
            best_by_segments[segments] = c
    deduped = list(best_by_segments.values())

    # parent_clause_id resolved from the COMPLETE set of captured
    # clause_ids, independent of extraction order (a merged/tall parent's
    # own code can be captured after its children's — see module docstring).
    by_segments: dict[tuple[int, ...], str] = {
        tuple(int(x) for x in re.split(r"[-.]", c["clause_id"])): c["clause_id"] for c in deduped
    }

    clauses: list[dict] = []
    for order_index, c in enumerate(deduped):
        segments = tuple(int(x) for x in re.split(r"[-.]", c["clause_id"]))
        parent_key = segments[:-1]
        parent_id = by_segments.get(parent_key) if parent_key else None
        clauses.append({**c, "parent_clause_id": parent_id, "order_index": order_index})

    return clauses


def _get_or_create_regulator(db: Session, code: str) -> Regulator:
    info = REGULATORS_BY_CODE.get(code)
    if info is None:
        raise SystemExit(f"Unknown regulator '{code}'. Known: {sorted(REGULATORS_BY_CODE)}")
    existing = db.scalar(select(Regulator).where(Regulator.code == code))
    if existing:
        return existing
    row = Regulator(code=info.code, name_en=info.name_en, name_ar=info.name_ar, weight=info.weight)
    db.add(row)
    db.flush()
    return row


def _get_or_create_regulation(db: Session, regulator: Regulator, code: str) -> Regulation:
    info = REGULATIONS_BY_CODE.get((regulator.code, code))
    if info is None:
        raise SystemExit(f"Unknown regulation '{code}' for regulator '{regulator.code}'.")
    existing = db.scalar(
        select(Regulation).where(Regulation.regulator_id == regulator.id, Regulation.code == code)
    )
    if existing:
        return existing
    row = Regulation(regulator_id=regulator.id, code=info.code, title_en=info.title_en, title_ar=info.title_ar)
    db.add(row)
    db.flush()
    return row


def _qdrant_point_id(regulator: str, regulation: str, version: str, clause_id: str, lang: str) -> str:
    return str(uuid.uuid5(uuid.NAMESPACE_URL, f"{regulator}/{regulation}/{version}/{clause_id}/{lang}"))


def ingest(
    regulator_code: str,
    regulation_code: str,
    version_label: str,
    file_path: Path,
    code_before_text: bool = False,
    replace: bool = False,
) -> None:
    if not file_path.is_file():
        raise SystemExit(
            f"Expected source file not found: {file_path}\n"
            f"Place the PDF there before running ingestion (see docs/PLAN.md section 1)."
        )

    print(f"\n{'='*60}\nXposure: Regulation Ingestion")
    print(f"Regulator/Regulation/Version: {regulator_code}/{regulation_code}/{version_label}")
    print(f"File: {file_path}")
    print(f"Ordering: {'code-before-text' if code_before_text else 'text-before-code'}")
    print(f"{'='*60}")

    file_bytes = file_path.read_bytes()
    file_sha256 = hashlib.sha256(file_bytes).hexdigest()

    engine = get_engine()
    with Session(engine) as db:
        regulator = _get_or_create_regulator(db, regulator_code)
        regulation = _get_or_create_regulation(db, regulator, regulation_code)

        existing_version = db.scalar(
            select(RegulationVersion).where(
                RegulationVersion.regulation_id == regulation.id,
                RegulationVersion.version_label == version_label,
            )
        )
        if existing_version is not None:
            if not replace:
                raise SystemExit(
                    f"Version '{version_label}' of {regulator_code}/{regulation_code} is already "
                    f"ingested (id={existing_version.id}, {len(existing_version.clauses)} clauses). "
                    f"regulation_version/clause rows are append-only: pass --replace to delete and "
                    f"re-ingest (dev convenience only; never do this for a version anyone has cited)."
                )
            print(f"[replace] Deleting existing version {existing_version.id} and its clauses...")
            for clause in existing_version.clauses:
                db.delete(clause)
            db.delete(existing_version)
            db.flush()
            _delete_qdrant_version(regulator_code, regulation_code, version_label)

        print("Extracting blocks...")
        blocks = extract_blocks(file_path)
        print(f"  {len(blocks)} content blocks")

        print("Parsing clauses...")
        parsed = parse_ecc_clauses(blocks, code_before_text)
        print(f"  {len(parsed)} clauses")
        if not parsed:
            raise SystemExit("Parsed zero clauses: the table-layout assumptions in parse_ecc_clauses() "
                              "don't match this file. Check a rendered page against the module docstring.")

        version = RegulationVersion(
            regulation_id=regulation.id,
            version_label=version_label,
            file_sha256=file_sha256,
        )
        db.add(version)
        db.flush()

        clause_rows = [
            Clause(
                version_id=version.id,
                clause_id=c["clause_id"],
                parent_clause_id=c["parent_clause_id"],
                text_en=c["text_en"],
                page_en=c["page_en"],
                order_index=c["order_index"],
            )
            for c in parsed
        ]
        db.add_all(clause_rows)
        db.commit()
        print(f"  Stored in Postgres: regulation_version.id={version.id}, {len(clause_rows)} clause rows")

        print("Embedding + indexing into Qdrant...")
        ensure_collection_exists()
        vectors = embed_passages([c["text_en"] for c in parsed])
        client = QdrantClient(host=settings.qdrant_host, port=settings.qdrant_port)
        points = [
            PointStruct(
                id=_qdrant_point_id(regulator_code, regulation_code, version_label, c["clause_id"], "en"),
                vector=vector,
                payload={
                    "regulator": regulator_code,
                    "regulation": regulation_code,
                    "version": version_label,
                    "clause_id": c["clause_id"],
                    "parent_clause_id": c["parent_clause_id"],
                    "lang": "en",
                    "text": c["text_en"],
                    "page": c["page_en"],
                },
            )
            for c, vector in zip(parsed, vectors)
        ]
        for i in range(0, len(points), 100):
            client.upsert(collection_name=settings.qdrant_collection, points=points[i:i + 100])
        print(f"  Indexed {len(points)} points into '{settings.qdrant_collection}'")

    print(f"\n{'='*60}\nDone.\n{'='*60}\n")


def _delete_qdrant_version(regulator_code: str, regulation_code: str, version_label: str) -> None:
    from qdrant_client.models import FieldCondition, Filter, MatchValue

    ensure_collection_exists()  # a brand-new Qdrant has no collection yet; deleting from it is a no-op anyway
    client = QdrantClient(host=settings.qdrant_host, port=settings.qdrant_port)
    client.delete(
        collection_name=settings.qdrant_collection,
        points_selector=Filter(must=[
            FieldCondition(key="regulator", match=MatchValue(value=regulator_code)),
            FieldCondition(key="regulation", match=MatchValue(value=regulation_code)),
            FieldCondition(key="version", match=MatchValue(value=version_label)),
        ]),
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Ingest a regulation PDF into Postgres + Qdrant")
    parser.add_argument("--regulator", required=True, help="e.g. nca")
    parser.add_argument("--regulation", required=True, help="e.g. ecc")
    parser.add_argument("--version", required=True, dest="version_label", help="e.g. 1-2018")
    parser.add_argument("--file", required=True, dest="file_path", type=Path)
    parser.add_argument(
        "--code-before-text", action="store_true",
        help="this file's table rows are CODE then TEXT (e.g. ECC-2:2024); omit for TEXT then CODE (e.g. ECC-1:2018) — see ingest.py's module docstring",
    )
    parser.add_argument("--replace", action="store_true", help="delete and re-ingest if this version already exists (dev only)")
    args = parser.parse_args()
    ingest(
        args.regulator, args.regulation, args.version_label, args.file_path,
        code_before_text=args.code_before_text, replace=args.replace,
    )
