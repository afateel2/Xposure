"""
Regulation ingestion: PDF -> versioned, control-ID-keyed clauses -> Postgres
(source of truth) + Qdrant (semantic search index).

Run as:
  python -m app.ingest --regulator nca --regulation ecc --version 1-2018 \
      --file "data/sources/nca/Essential Cybersecurity Controls (ECC-1-2018).pdf"
  python -m app.ingest --regulator nca --regulation ecc --version 2-2024 \
      --file "data/sources/nca/Essential Cybersecurity Controls (ECC-2-2024).pdf" \
      --code-before-text

Parsing strategy is NCA-ECC-specific, not a generic port of ComplyX's
chunk_into_articles(): both source PDFs render as a two-column table
(code | text), confirmed by rendering real pages (see docs/PLAN.md section
1) — but ComplyX's leading-marker assumption ("Article 1: ...") doesn't fit
either convention this table format actually uses, which is why this file
doesn't reuse that code despite it being the closest fit in the source repo.

This module works at the PDF BLOCK level (fitz page.get_text("blocks")),
not the flattened page-text level ComplyX's chunker uses, because the two
ECC editions were generated by different tooling and order their table
cells oppositely — confirmed by dumping raw block bounding boxes for both,
not assumed from visual similarity (a first pass assumed ECC-2:2024 would
match ECC-1:2018's ordering since the rendered tables look the same; it
doesn't, and trusting that without checking would have silently mislabeled
most of ECC-2's clauses):
  - ECC-1:2018: within a block, a row's TEXT precedes its CODE line
    ("Networks Security Management\n2-5\n").
  - ECC-2:2024: within a block, a row's CODE precedes its TEXT
    ("1-5 \nCybersecurity Risk Management \n"), and its dotted subcontrols
    are inline-prefixed on one line ("1.5.3.1 At early stage of technology
    projects.") rather than on a separate bare-code line at all.
Which convention a file uses is passed explicitly via --code-before-text
rather than auto-detected: there are exactly two known ECC source files,
and a heuristic classifier for a two-document
problem is exactly the kind of premature abstraction the project's own
ground rules say to avoid. A third regulator PDF that doesn't fit either
convention should get its own explicit case here, not a guesser.

For a "tall" row whose content spans several sub-items (e.g. "2-5-3"
covering eight sub-controls), PyMuPDF splits the code and its content into
separate blocks — confirmed the block ORDER still keeps them adjacent and
correctly sequenced in both documents' conventions, which is what makes
processing blocks in order, rather than re-deriving position from
scratch, a reliable strategy here.

On a tall row in a text-before-code document, a parent's own lead-in
sentence lands attributed to its first child instead of the parent (no
code line ever separates them), which would otherwise leave the parent
with no text of its own and drop it entirely. _recover_dropped_parent_intros()
recovers this post-hoc: the lead-in always ends in a colon before the
enumerated sub-items begin (confirmed against the real text — "...must
include at least the following:" — not assumed), which is a much more
reliable split signal than it first appears; an earlier version of this
function tried splitting on PyMuPDF BLOCK boundaries instead, on the
theory that the intro and the child's own text land in separate blocks,
but checking the real block dump disproved that (a single wrapped
sentence gets split across two blocks purely from line-wrapping in a
narrow column, unrelated to any semantic boundary). When no colon is
found in a plausible position, the parent is left dropped rather than
guessing — real verbatim text on the sibling, not fabricated or lost.

ECC-1:2018 codes are all hyphen-separated ("2-5-3-1"); ECC-2:2024 mixes
hyphens for main controls ("1-10-3") and dots for its subcontrols
("1.10.3.1") — confirmed by rendering both, not assumed. parent_clause_id
is resolved by normalizing every code to an integer tuple and looking up
the tuple with its last segment dropped, so the hyphen/dot mismatch
across levels doesn't break the parent link.

Also confirmed by rendering (not assumed): some subdomain/domain codes
appear a second time in an early overview table/figure that lists every
code next to just its short title, in the identical code|text shape as a
real row (ECC-1:2018 page 12, "Figure (2): ECC Subdomains"). When a
clause_id repeats within one version, the occurrence with more
substantive text wins — the overview entries are consistently short-title
only, a direct content signal rather than a positional guess.
"""

